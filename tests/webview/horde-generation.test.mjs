import { expect, test } from '@rstest/core';
import { createFrontend } from '../helpers/frontend.mjs';

const { window, load, startHost } = await createFrontend();
const started = [];
let stream = { events: [], status: 'done' };
let startFailure = null;
const invoke = window.__TAURI__.core.invoke;
window.__TAURI__.core.invoke = async (command, args, options) => {
    switch (command) {
        case 'get_horde_text_models':
            return [{ name: 'model-a', count: 1, eta: 0, performance: 1, queued: 0 }];
        case 'get_horde_text_workers':
            return [];
        case 'start_horde_text_stream':
            started.push(args.dto);
            if (startFailure) {
                throw startFailure;
            }
            return null;
        case 'read_generation_stream':
            return stream;
        case 'close_generation_stream':
            return true;
        default:
            return invoke(command, args, options);
    }
};

await startHost();
const { generateHorde, getHordeModels, horde_settings } = await load('scripts/horde.js');
horde_settings.models = ['model-a'];
await getHordeModels(true);

function finished(...chunks) {
    const events = [...chunks, '[DONE]'].map((data, index) => ({ type: 'chunk', seq: index + 1, data }));
    return { events: [...events, { type: 'done', seq: events.length + 1 }], status: 'done' };
}

const signal = () => new window.AbortController().signal;

test('a Horde generation sends the page request and returns the generation its task reports', async () => {
    stream = finished(
        JSON.stringify({ done: false, queue_position: 2 }),
        JSON.stringify({ done: true, generations: [{ text: 'Hello', worker_name: 'Worker', model: 'model-a' }] }),
    );

    const result = await generateHorde('Prompt', { prompt: 'Prompt', type: 'normal', max_length: 80 }, signal(), true);

    expect(result).toEqual({ text: 'Hello', workerName: 'Generated by Horde worker: Worker [model-a]' });
    expect(started.at(-1)).toEqual({
        prompt: 'Prompt',
        params: { max_length: 80, n: 1, frmtadsnsp: false, frmtrmblln: false, frmtrmspch: false, frmttriminc: false },
        trusted_workers: false,
        models: ['model-a'],
        type: 'normal',
    });
});

test('a failed Horde task reads as the reply, and a quiet request throws whether queuing or polling fails', async () => {
    stream = { events: [{ type: 'error', seq: 1, message: 'Horde request faulted. Please try again.' }], status: 'error' };
    expect(await generateHorde('Prompt', { type: 'normal' }, signal(), false)).toEqual({
        text: '[API Error]\nHorde request faulted. Please try again.',
        workerName: undefined,
    });
    await expect(generateHorde('Prompt', { type: 'quiet' }, signal(), false))
        .rejects.toThrow('Horde generation failed: Horde request faulted. Please try again.');

    startFailure = { Forbidden: 'iOS policy disabled capability: ai.horde' };
    try {
        await expect(generateHorde('Prompt', { type: 'quiet' }, signal(), false))
            .rejects.toThrow('Horde generation failed: iOS policy disabled capability: ai.horde');
    } finally {
        startFailure = null;
    }
});
